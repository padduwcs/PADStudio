// These messages are application-owned API presentation copy. Keep the API contract intact and preserve its values.
export function translateApplicationMessage(source) {
  if (typeof source !== "string") return source;
  const connection = /^Kết nối được: (\d+) giọng, (\d+) model(?:, đã dùng ([\d.,]+)\/([\d.,]+) ký tự\.)?\.?$/.exec(source);
  if (connection) return `Connected: ${connection[1]} voices, ${connection[2]} models` + (connection[3] ? `, ${connection[3]}/${connection[4]} characters used.` : ".");
  const capability = /^Công cụ cho ([\w.-]+)\.$/.exec(source);
  return capability ? `Tool for ${capability[1]}.` : source;
}
